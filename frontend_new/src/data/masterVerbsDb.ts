export const WORD_MAP: Record<string, VerbEntry> = {};
MASTER_VERBS_DB.forEach((v) => {
  WORD_MAP[v.word] = v;
});

export const TOTAL_VERBS = MASTER_VERBS_DB.length;
export const BATCH_SIZE = 30;
export const TOTAL_BATCHES = Math.ceil(TOTAL_VERBS / BATCH_SIZE);

export const ANAGRAM_MAP: Record<string, VerbEntry[]> = {};
MASTER_VERBS_DB.forEach((v) => {
  const rack = getAnagramRack(v.word);
  if (!ANAGRAM_MAP[rack]) {
    ANAGRAM_MAP[rack] = [];
  }
  ANAGRAM_MAP[rack].push(v);
});

export function getBatchWords(batchIndex: number): VerbEntry[] {
  const start = (batchIndex * BATCH_SIZE) % TOTAL_VERBS;
  const out: VerbEntry[] = [];
  for (let i = 0; i < BATCH_SIZE; i++) {
    const idx = (start + i) % TOTAL_VERBS;
    out.push(MASTER_VERBS_DB[idx]);
  }
  return out;
}

export function normalizeStr(str: string): string {
  return str.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toUpperCase();
}

export function getAnagramRack(word: string): string {
  const cleanWord = normalizeStr(word);
  return cleanWord.split("").sort().join("");
}

export function shuffleArray<T>(arr: T[]): T[] {
  return [...arr].sort(() => Math.random() - 0.5);
}

export function buildTrainingSequence(words: string[]): string[] {
  return shuffleArray(words).concat(shuffleArray(words));
}
